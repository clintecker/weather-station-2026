def rows(art):
    """The 16 rows of a glyph as 16-bit numbers, bit w - 1 the leftmost pixel, and its width w."""
    w = len(art[0])
    assert len(art) == H and all(len(r) == w for r in art) and w <= 16, art
    return [int(r.replace('#', '1').replace('.', '0'), 2) for r in art], w


def generate():
    chars = ''.join(sorted(GLYPHS))
    lines = ['/* GENERATED by firmware/stage0-node/tools/make_scr_font.py: do not edit. Edit the script and re-run it. */',
             '#include "scr_font.h"', '',
             f'static const char scr_big_chars[] = "{chars}";', '',
             '/* Each glyph\'s width, then its 16 rows, top first; bit w - 1 is the leftmost column. */',
             f'static const uint8_t scr_big_w[{len(chars)}] = {{ ' + ', '.join(str(rows(GLYPHS[c])[1]) for c in chars) + ' };', '',
             f'static const uint16_t scr_big_rows[{len(chars)}][SCR_BIG_H] = {{']
    for c in chars:
        body = ', '.join(f'0x{r:04X}' for r in rows(GLYPHS[c])[0])
        lines.append(f"  {{ {body} }},   /* '{c}' */")
    lines += ['};', '',
              f'const oled_font scr_big = {{ .h = SCR_BIG_H, .w = 10, .bits = 16, .gap = 2, .n = {len(chars)}, '
              '.chars = scr_big_chars,',
              "                          .widths = scr_big_w, .rows = scr_big_rows, .missing = '\\0' };", '']
    return '\n'.join(lines)


def main():
    text = generate()
    if '--check' in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f'{OUT} is out of date: run {Path(__file__).name}', file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
