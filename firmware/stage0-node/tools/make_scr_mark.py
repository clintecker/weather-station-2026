"""Write firmware/stage0-node/App/scr_mark.c: the LGTM SYSTEMS wordmark of the boot splash, drawn here as text so it
can be read and checked.

    python3 firmware/stage0-node/tools/make_scr_mark.py          # rewrite the C file
    python3 firmware/stage0-node/tools/make_scr_mark.py --check  # exit 1 if the C file is out of date

Original lettering (2026-11-09): L, G, T and M, 14 pixels wide and 13 tall in 2-pixel strokes, square-cornered and
wide, each cut through by one dark row (row 6), the wordmark's slit. App/scr_boot.c spaces them wide (oled_style's
pitch) and draws them with a dim halo for the glow. tests/test_scr_view.py runs --check."""
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1]/'App/scr_mark.c'
H, W, SLIT = 13, 14, 6

GLYPHS = {
    'L': ['##............', '##............', '##............', '##............', '##............', '##............',
          '..............', '##............', '##............', '##............', '##............', '##############',
          '##############'],
    'G': ['..############', '.#############', '##............', '##............', '##............', '##.....#######',
          '..............', '##.....#######', '##..........##', '##..........##', '##..........##', '.#############',
          '..###########.'],
    'T': ['##############', '##############', '......##......', '......##......', '......##......', '......##......',
          '..............', '......##......', '......##......', '......##......', '......##......', '......##......',
          '......##......'],
    'M': ['###........###', '####......####', '##.##....##.##', '##..##..##..##', '##...####...##', '##....##....##',
          '..............', '##..........##', '##..........##', '##..........##', '##..........##', '##..........##',
          '##..........##'],
}


def rows(art):
    """The 13 rows of a glyph as 16-bit numbers, bit 13 the leftmost pixel (oled_font.h: bit w - 1)."""
    assert len(art) == H and all(len(r) == W for r in art) and set(art[SLIT]) == {'.'}, art
    return [int(r.replace('#', '1').replace('.', '0'), 2) for r in art]


def generate():
    chars = ''.join(GLYPHS)
    lines = ['/* GENERATED by firmware/stage0-node/tools/make_scr_mark.py: do not edit. Edit the script and re-run it. */',
             '#include "scr_mark.h"', '',
             f'static const char scr_mark_chars[] = "{chars}";', '',
             '/* Each glyph\'s 13 rows, top first; bit 13 is the leftmost column. */',
             f'static const uint16_t scr_mark_rows[{len(chars)}][SCR_MARK_H] = {{']
    for c in chars:
        lines.append(f"  {{ {', '.join(f'0x{r:04X}' for r in rows(GLYPHS[c]))} }},   /* '{c}' */")
    lines += ['};', '',
              f'const oled_font scr_mark = {{ .h = SCR_MARK_H, .w = SCR_MARK_W, .bits = 16, .gap = 0, .n = {len(chars)}, '
              '.chars = scr_mark_chars,',
              "                           .widths = NULL, .rows = scr_mark_rows, .missing = '\\0' };", '']
    return '\n'.join(lines)


def main():
    text = generate()
    if '--check' in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f'{OUT} is out of date: run {Path(__file__).name}', file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
