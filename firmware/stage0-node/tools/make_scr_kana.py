def rows(art, mirror=True):
    """The 7 rows of a glyph, bit 4 the leftmost pixel; mirrored left to right unless mirror is False."""
    rs = art.split()
    assert len(rs) == H and all(len(r) == W and set(r) <= {'#', '.'} for r in rs), art
    return [int((r[::-1] if mirror else r).replace('#', '1').replace('.', '0'), 2) for r in rs]


def generate():
    names = list(GLYPHS)
    lines = ['/* GENERATED by firmware/stage0-node/tools/make_scr_kana.py: do not edit. Edit the script and re-run it. */',
             '#include "scr_kana.h"', '',
             '/* Each glyph mirrored, its 7 rows top first; bit 4 is the leftmost column. */',
             f'static const uint8_t scr_kana_rows[{len(names)}][SCR_KANA_H] = {{']
    for name in names:
        body = ', '.join(f'0x{r:02X}' for r in rows(GLYPHS[name]))
        lines.append(f'  {{ {body} }},   /* {name} */')
    lines += ['};', '',
              f'const oled_font scr_kana = {{ .h = SCR_KANA_H, .w = SCR_KANA_W, .bits = 8, .gap = 1, .n = {len(names)}, '
              '.chars = NULL,',
              "                           .widths = NULL, .rows = scr_kana_rows, .missing = '\\0' };", '']
    return '\n'.join(lines)


def main():
    text = generate()
    if '--check' in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f'{OUT} is out of date: run {Path(__file__).name}', file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
