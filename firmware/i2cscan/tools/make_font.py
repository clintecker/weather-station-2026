def rows(art):
    """The 7 rows of a glyph as 5-bit numbers, bit 4 the leftmost pixel."""
    out = [int(r.replace('#', '1').replace('.', '0'), 2) for r in art.split()]
    assert len(out) == 7 and all(len(r) == 5 for r in art.split()), art
    return out


def generate():
    chars = ''.join(sorted(GLYPHS))
    lines = ['/* GENERATED by firmware/i2cscan/tools/make_font.py: do not edit. Edit the script and re-run it. */',
             '#include "font5x7.h"', '',
             f'const char font5x7_chars[] = "{chars}";', '',
             '/* One glyph a line: 7 rows, top first; bit 4 is the leftmost of the 5 columns. */',
             f'const uint8_t font5x7_rows[{len(chars)}][FONT5X7_H] = {{']
    for c in chars:
        body = ', '.join(f'0x{r:02X}' for r in rows(GLYPHS[c]))
        lines.append(f"  {{ {body} }},   /* '{c}' */")
    lines += ['};', '']
    return '\n'.join(lines)


def main():
    text = generate()
    if '--check' in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f'{OUT} is out of date: run {Path(__file__).name}', file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
