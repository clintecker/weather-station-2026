"""Step 4 and 5 outputs, generated from build.py and routing.py: wiring-plan.md (placement, board by board
build order, BOJACK cut list, every lead with its routed length) and homes.md (what lives off the
breadboards). Pictures are the KiCad renders (kicad_layout.py --render). Refuses while build.check() fails.
Run: python3 outputs.py
"""
import math
import sys
from collections import defaultdict

import build as b
import routing

SLACK = 1.10                       # routed 3D length + 10 % for the bends at each end
DUPONT_SIZES = (100, 200, 300)     # mm, the usual kit lengths
QT_COLOUR = {"GND": "black", "V+": "red (3V3)", "SDA": "blue", "SCL": "yellow"}
NUCLEO_PIN = {"CN5.9": "D14 SDA", "CN5.10": "D15 SCL", "CN9.5": "D4", "CN9.6": "D5", "CN9.7": "D6",
              "CN8.1": "A0", "CN8.2": "A1", "CN8.3": "A2", "CN8.4": "A3", "CN6.4": "3V3", "CN6.6": "GND",
              "CN6.7": "GND", "CN5.7": "GND", "CN7.16": "morpho 3V3", "CN10.20": "morpho GND",
              "CN10.11": "morpho PA5", "CN10.15": "morpho PA7", "CN10.17": "morpho PA4", "CN10.21": "morpho PC2",
              "CN10.23": "morpho PC1"}
KIND_TEXT = {"force": "20 AWG force leads", "pigtail": "JST PH pigtails (#1131 halves)", "solder": "22 AWG soldered leads",
             "sense": "22 AWG sense leads", "reg": "22 AWG regulator lead", "lead": "component leads into WAGOs",
             "qt": "STEMMA QT cables", "mate": "plug-in matings (no wire)", "cable": "external cables"}


def name(end):
    if isinstance(end, str):
        return f"{end.split(':')[0]} {b.label(end)}"
    ref, pin = end
    if ref == "A1":
        return f"TX NUCLEO {pin} ({NUCLEO_PIN.get(pin, pin)})"
    return f"{ref}.{pin}"


def order_key(hole):
    _x, _y, row, col = b.hole_xy(hole)
    return -col, b.ROW_ORDER.index(row)          # column 62 (left) first, then top to bottom


def routed():
    routes, problems = routing.report()
    if problems:
        sys.exit("routing problems:\n" + "\n".join(problems))
    pl = routing.base_plan()
    return {k: sum(math.dist(p, q) for p, q in zip(pts, pts[1:]))
            for k, r in routes.items() for pts in [routing.drape(pl, r)]}


def buy(mm):
    return next((s for s in DUPONT_SIZES if mm * SLACK <= s), None)


# ------------------------------------------------------------------ wiring-plan.md
def plan_md(mm):
    duponts = [(k, c) for k, c in enumerate(b.CONDUCTORS) if c[0] == "dupont"]
    dnum = {k: f"D{i}" for i, (k, _c) in enumerate(duponts, 1)}
    flags = []

    L = ["# Breadboard bench r1: wiring plan", "",
         "Generated by `layout/outputs.py` from `build.py` (checked against `../schematic/model.py`) and",
         "`routing.py`; do not edit by hand.", "",
         "Holes are named the way the Elegoo boards are printed: `BB1:h24` is board 1, row h, column 24. Rows a-e",
         "are the upper half, top to bottom, f-j the lower half; column 62 is at the left, column 1 at the right.",
         "Rail holes are named by their job and side: `GND ↓52` is the blue - rail along the bottom edge, straight",
         "below column 52; `3V3 ↑18` the red + rail along the top edge above column 18. Every + rail is 3V3 and every",
         "- rail is logic ground. Plate positions are mm from the back-left corner, x to the right, y towards you.", "",
         "Pictures: [plate top](kicad/plate-top.png), [plate iso](kicad/plate-iso.png), and per board",
         "[BB1](kicad/BB1-top.png) ([iso](kicad/BB1-iso.png)), [BB2](kicad/BB2-top.png) ([iso](kicad/BB2-iso.png)),",
         "[BB3](kicad/BB3-top.png) ([iso](kicad/BB3-iso.png)). The KiCad boards are in `kicad/`.", "",
         "## 1. Breadboards", "", "| Board | Job | Top-left on the plate (mm) |", "|---|---|---|"]
    for bd, (x, y) in b.BOARDS.items():
        L.append(f"| {bd} | {b.BOARD_ROLE[bd]} | ({x:.0f}, {y:.0f}) |")

    L += ["", "## 2. Board by board", "",
          "Build each board in this order: flat jumpers, then leaded parts, then the seated modules, then the",
          "flying wires. Wire numbers (D1 ...) match section 4.", ""]
    for bd in b.BOARDS:
        L += [f"### {bd}: {b.BOARD_ROLE[bd]}", ""]
        jumpers = sorted((c for c in b.CONDUCTORS if c[0] == "jumper" and c[1].startswith(bd + ":")),
                         key=lambda c: order_key(c[1]))
        if jumpers:
            L += ["**Jumpers (BOJACK, flat)**", "", "| From | To | Span | What |", "|---|---|---|---|"]
            L += [f"| {b.label(c[1])} | {b.label(c[2])} | {b.span(c[1], c[2])} | {c[3]} |" for c in jumpers]
            L.append("")
        leaded = defaultdict(dict)
        for (ref, pin), hole in b.ON_BB.items():
            if hole.startswith(bd + ":") and ref not in b.PLACE and ref[:2] not in ("W1", "W2", "W3"):
                leaded[ref][pin] = hole
        if leaded:
            L += ["**Leaded parts**", "", "| Ref | Value | Holes | Note |", "|---|---|---|---|"]
            for ref in sorted(leaded, key=lambda r: min(order_key(h) for h in leaded[r].values())):
                holes = ", ".join(f"{p} {b.label(h)}" for p, h in sorted(leaded[ref].items(), key=lambda ph: order_key(ph[1])))
                note = "bead taped to the pack; its leads end here" if ref == "RT1" else (
                    "lies flat; holes between its leads stay empty" if ref.startswith("R") else "")
                if ref.startswith("C") and "+" in leaded[ref]:
                    note = "electrolytic: + lead in the hole marked +"
                L.append(f"| {ref} | {b.PART[ref]['value']} | {holes} | {note} |")
            L.append("")
        seated = [r for r, pl in b.PLACE.items() if "seat" in pl and pl["seat"][1].startswith(bd + ":")]
        if seated:
            L += ["**Seated modules (by their header)**", "", "| Ref | Part | Header, left to right | Held |", "|---|---|---|---|"]
            for ref in sorted(seated, key=lambda r: order_key(b.PLACE[r]["seat"][1])):
                kind = b.PLACE[ref]["kind"]
                pins = sorted(b.HEADER[kind], key=lambda p: order_key(b.ON_BB[(ref, p)]))
                row = ", ".join(f"{p.replace('H.', '')} {b.label(b.ON_BB[(ref, p)])}" for p in pins)
                L.append(f"| {ref} | {b.PART[ref]['part']} {b.PART[ref]['value']} | {row} | {b.PLACE[ref]['held']} |")
            L.append("")
        ends = []
        for k, c in enumerate(b.CONDUCTORS):
            for e, other in ((c[1], c[2]), (c[2], c[1])):
                if isinstance(e, str) and e.startswith(bd + ":") and c[0] != "jumper":
                    what = f"{dnum[k]} Dupont" if c[0] == "dupont" else KIND_TEXT[c[0]].rstrip("s")
                    ends.append((e, what, name(other), c[3]))
        for (ref, pin), hole in b.ON_BB.items():
            if hole.startswith(bd + ":") and ref in ("W1", "W2", "W3"):
                if ref == "W1":
                    ends.append((hole, "W1 ground tie", "STAR WAGO lever 4", "22 AWG solid, the one ground tie"))
                else:
                    sig = pin.split(".")[1]
                    ends.append((hole, f"{ref} QT-to-header, {QT_COLOUR[sig]} pin", sig, b.PART[ref]["value"]))
        if ends:
            L += ["**Wire ends in this board**", "", "| Hole | Wire | Goes to | Note |", "|---|---|---|---|"]
            L += [f"| {b.label(h)} | {w} | {o} | {n} |" for h, w, o, n in sorted(ends, key=lambda e: order_key(e[0]))]
            L.append("")

    L += ["## 3. BOJACK cut list", "", "| Span (holes) | Count | Runs |", "|---|---|---|"]
    by_span = defaultdict(list)
    for c in b.CONDUCTORS:
        if c[0] == "jumper":
            by_span[b.span(c[1], c[2])].append(f"{c[1].split(':')[0]} {b.label(c[1])} to {b.label(c[2])}")
    L += [f"| {s} | {len(v)} | {', '.join(v)} |" for s, v in sorted(by_span.items())]
    L += ["", f"{sum(map(len, by_span.values()))} jumpers, all straight kit lengths.", ""]

    L += ["## 4. Dupont wires", "",
          f"Length is along the routed path in 3D (out of the housing, over what is under it, into the far end).",
          f"Buy the smallest kit length that is at least {SLACK:.2f} x that. M = pin end, F = socket end:",
          "breadboard to an Arduino socket is M-M, breadboard to a morpho pin is M-F.", "",
          "| # | From | To | Type | Routed mm | Buy | What |", "|---|---|---|---|---|---|---|"]
    tally = defaultdict(int)
    for k, c in duponts:
        d = mm[f"dupont:{k}"]
        size = buy(d)
        if size is None:
            flags.append(f"{dnum[k]} needs about {d * SLACK:.0f} mm, longer than any kit Dupont")
        gender, what = c[3].split(": ", 1)
        tally[(gender, size)] += 1
        L.append(f"| {dnum[k]} | {name(c[1])} | {name(c[2])} | {gender} | {d:.0f} | {size or '?'} | {what} |")
    L += ["", "Shopping: " + ", ".join(f"{n} x {g} {s // 10} cm" for (g, s), n in sorted(tally.items())) + ".", ""]

    L += ["## 5. Routed leads with a limit", "", "| Lead | Routed mm | Limit mm | |", "|---|---|---|---|"]
    limited = [(f"W1 ground tie (STAR to {b.PART_SPANS['W1'][1]})", mm["W1"], b.PART_SPANS["W1"][2])]
    limited += [(f"regulator lead ({name(c[1])} to {c[2]})", mm[f"reg:{k}"], b.LIMIT_MM["reg"])
                for k, c in enumerate(b.CONDUCTORS) if c[0] == "reg"]
    limited += [(f"{w} QT-to-header cable ({'sensor' if w == 'W2' else 'power'} branch)", mm[w], b.QT_HEADER_MM)
                for w in ("W2", "W3")]
    for what, d, lim in limited:
        ok = d <= lim
        if not ok:
            flags.append(f"{what}: routed {d:.0f} mm, limit {lim} mm")
        L.append(f"| {what} | {d:.0f} | {lim} | {'ok' if ok else '**over**'} |")
    ntc = max(mm["RT1:1"], mm["RT1:2"])
    L += ["", f"NTC (RT1) leads: about {ntc:.0f} mm from the bead on the pack to BB1 c38/c39; extend the #372's "
          "leads if they are shorter [TBD-MEASURE].", ""]

    L += ["## 6. Everything else", "",
          "Off the breadboards: straight-line estimate x 1.15 + 10 mm (these runs are short and in the open).", ""]
    for kind in ("pigtail", "force", "solder", "sense", "lead", "qt", "mate", "cable"):
        cs = [c for c in b.CONDUCTORS if c[0] == kind and c[1][0] != "W1"]   # W1 is in section 5
        if not cs:
            continue
        L += [f"### {KIND_TEXT[kind]} ({len(cs) // (4 if kind == 'qt' else 1)})", ""]
        if kind == "qt":
            L += ["| From | To | What |", "|---|---|---|"]
            L += [f"| {c[1][0]} {c[1][1].split('.')[0]} | {c[2][0]} {c[2][1].split('.')[0]} | {c[3]} |"
                  for c in cs if c[1][1].endswith(".GND")]
        else:
            L += ["| From | To | About mm | What |", "|---|---|---|---|"]
            for c in cs:
                p1, p2 = b.pin_xy(c[1]), b.pin_xy(c[2])
                d = "-" if p1 is None or p2 is None or kind in ("mate", "cable") else f"{math.dist(p1, p2) * 1.15 + 10:.0f}"
                L.append(f"| {name(c[1])} | {name(c[2])} | {d} | {c[3]} |")
        L.append("")

    L += ["## 7. Open items", ""]
    L += [f"- **{f}**" for f in flags]
    L += ["- Header pin positions on the modules and the NUCLEO are estimates [TBD-MEASURE]; check each seat before "
          "pressing it in.",
          "- BOB-14021 pin 1 side, and the #5978 and #369 plugs fitted together in the #4755 [TBD-MEASURE].", ""]
    return "\n".join(L) + "\n", flags


# ------------------------------------------------------------------ homes.md
def homes_md():
    L = ["# Breadboard bench r1: homes off the breadboards", "",
         f"Generated by `layout/outputs.py`. Everything that does not sit in a breadboard hole, on the "
         f"{b.PLATE_W} x {b.PLATE_H} mm plate. Positions are the top-left corner of the outline after rotation, mm "
         "from the plate's back-left corner (x right, y towards you). See [plate top](kicad/plate-top.png).", "",
         "| Ref | Part | Outline (mm) | At (x, y) | Turned | Holder |", "|---|---|---|---|---|---|"]
    for ref, pl in b.PLACE.items():
        if "at" not in pl:
            continue
        x, y, w, h = b.outline(ref)
        L.append(f"| {ref} | {b.PART[ref]['part']} ({b.PART[ref]['value']}) | {w:.1f} x {h:.1f} | ({x:.0f}, {y:.0f}) "
                 f"| {pl['rot']} | {pl['held']} |")
    L += ["", "Riding in another part: " + "; ".join(f"{r} {pl['held']}" for r, pl in b.PLACE.items() if "mate" in pl) + ".",
          "", "## Not fixed to the plate", "", "| Item | Home |", "|---|---|",
          "| RT1 NTC | bead taped to the pack, leads to BB1 c38/c39 |",
          "| Pack lead and plug | its own 100 mm lead brings the plug to the CELL+ and STAR WAGOs |",
          "| Weather meter cables (wind, rain) | enter at the front edge into the RJ11 jacks on BB3 |",
          "| Solar panel lead, USB-C adapter cable | enter at the left edge into the #368 and #4090 |",
          "| TX and RX ST-LINK USB cables | to the Mac, each on its own port |",
          "| Dupont bundles | one adhesive cable clip per bundle: BB1 to the TX NUCLEO, BB3 to the TX NUCLEO |", ""]
    return "\n".join(L) + "\n"


def write():
    fails, _notes = b.check()
    if fails:
        sys.exit("build.check() fails; fix build.py first:\n" + "\n".join(fails))
    text, flags = plan_md(routed())
    (b.HERE / "wiring-plan.md").write_text(text)
    (b.HERE / "homes.md").write_text(homes_md())
    print("wrote wiring-plan.md, homes.md")
    for f in flags:
        print("flag ", f)


if __name__ == "__main__":
    write()
